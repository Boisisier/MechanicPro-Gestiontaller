const normalize = (value: string) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();

export const vehicleBrandNames = Object.keys(vehicleModelCatalog).sort((a, b) =>
  a.localeCompare(b, "es"),
);

export const getModelsForBrand = (brand: string) => {
  const normalizedBrand = normalize(brand);
  const matchedBrand = vehicleBrandNames.find((item) => normalize(item) === normalizedBrand);
  return matchedBrand ? vehicleModelCatalog[matchedBrand] : [];
};
